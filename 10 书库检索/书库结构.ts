/** 章号类单元格允许的写法；空、破折号、「未定」都算没写。 */
export const 章号样式 = /^(?:ch\s*\d+|第?\s*\d+\s*章?|\d{1,4})$/i

export function 是章号值(值: string): boolean {
  const 干净 = String(值 ?? "").trim()
  if (!干净 || 干净 === "—" || 干净 === "-" || 干净 === "未定") return true
  return 干净.split(/[／/、,，;；\s]+/).every((片) => 片 === "" || 章号样式.test(片))
}

export function 是数字值(值: string): boolean {
  const 干净 = String(值 ?? "").trim().replace(/章$/, "")
  if (!干净 || 干净 === "—" || 干净 === "-" || 干净 === "未定") return true
  return /^\d+(\.\d+)?$/.test(干净)
}

export const 日期样式 = /^(?:\d{4}-\d{2}-\d{2}|\d{1,2}月\d{1,2}日|第\d+日|\d{1,2}\/\d{1,2}.*)$/

export function 是日期值(值: string): boolean {
  const 干净 = String(值 ?? "").trim()
  if (!干净 || 干净 === "—" || 干净 === "-" || 干净 === "未定") return true
  return 日期样式.test(干净)
}

/** 按列规范判断一格值合不合法。 */
export function 值符合(类型: 列类型, 值: string): boolean {
  if (类型 === "章号") return 是章号值(值)
  if (类型 === "数字") return 是数字值(值)
  if (类型 === "日期") return 是日期值(值)
  return true
}

/** 表头里找某一列（认别名，包含即可）。 */
export function 找列(表头: string[], 规范: 列规范): number {
  const 名们 = [规范.名称, ...(规范.别名 ?? [])]
  return 表头.findIndex((头) => 名们.some((名) => 头.includes(名)))
}
