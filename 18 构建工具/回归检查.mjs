// ────────────────────────── 自实现的极简断言 ──────────────────────────

const 断言 = {
  相等(实际, 期望, 说明) {
    const 甲 = JSON.stringify(实际)
    const 乙 = JSON.stringify(期望)
    if (甲 !== 乙) throw new Error(说明 + "：期望 " + 乙 + "，实际 " + 甲)
  },
  为真(条件, 说明) {
    if (!条件) throw new Error(说明 + "：期望为真，实际为假")
  },
  为假(条件, 说明) {
    if (条件) throw new Error(说明 + "：期望为假，实际为真")
  },
  含(原文, 片段, 说明) {
    const 文本 = typeof 原文 === "string" ? 原文 : JSON.stringify(原文)
    if (!文本.includes(片段)) throw new Error(说明 + "：没找到「" + 片段 + "」")
  },
  不含(原文, 片段, 说明) {
    const 文本 = typeof 原文 === "string" ? 原文 : JSON.stringify(原文)
    if (文本.includes(片段)) throw new Error(说明 + "：不该出现「" + 片段 + "」")
  },
  抛错(执行, 说明, 片段) {
    let 抛了 = false
    let 错误 = null
    try {
      执行()
    } catch (错) {
      抛了 = true
      错误 = 错
    }
    if (!抛了) throw new Error(说明 + "：本应抛错，却顺利返回")
    if (片段 && !String(错误 && 错误.message).includes(片段)) {
      throw new Error(说明 + "：错误文案不符（" + String(错误 && 错误.message) + "）")
    }
  },
}

// ────────────────────────── 用例运行器 ──────────────────────────

const 记账 = { 通过: 0, 失败: 0, 毫秒: 0, 失败清单: [] }

async function 用例(组, 名称, 执行) {
  const 起 = performance.now()
  try {
    await 执行()
    const 耗时 = performance.now() - 起
    记账.通过++
    记账.毫秒 += 耗时
    console.log("  ✅ " + 名称 + "（" + 耗时.toFixed(1) + "ms）")
  } catch (错误) {
    const 耗时 = performance.now() - 起
    记账.失败++
    记账.毫秒 += 耗时
    const 文案 = String((错误 && 错误.message) || 错误)
    记账.失败清单.push({ 组, 名称, 文案 })
    console.log("  ❌ " + 名称 + "（" + 耗时.toFixed(1) + "ms）")
    console.log("     " + 文案)
  }
}

