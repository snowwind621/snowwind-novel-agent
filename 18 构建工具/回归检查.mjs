// ─────────────────── 自带 CRC32 与 ZIP 读取（用来校验导出的 docx / epub） ───────────────────

const CRC表 = (() => {
  const 表 = new Int32Array(256)
  for (let i = 0; i < 256; i++) {
    let c = i
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    表[i] = c
  }
  return 表
})()

function crc32(数据) {
  let c = -1
  for (let i = 0; i < 数据.length; i++) c = CRC表[(c ^ 数据[i]) & 0xff] ^ (c >>> 8)
  return (c ^ -1) >>> 0
}

/** 只认「存储不压缩」的 ZIP（导出的 docx/epub 正是如此），顺便验 CRC。 */
function 读ZIP(数据) {
  let 尾 = 数据.length - 22
  while (尾 >= 0 && 数据.readUInt32LE(尾) !== 0x06054b50) 尾--
  if (尾 < 0) throw new Error("不是 ZIP：找不到中央目录结束记录")
  const 条数 = 数据.readUInt16LE(尾 + 10)
  let 游标 = 数据.readUInt32LE(尾 + 16)
  const 条目们 = []
  for (let i = 0; i < 条数; i++) {
    if (数据.readUInt32LE(游标) !== 0x02014b50) throw new Error("ZIP 中央目录损坏，偏移 " + 游标)
    const 方法 = 数据.readUInt16LE(游标 + 10)
    const 校验和 = 数据.readUInt32LE(游标 + 16)
    const 压缩后 = 数据.readUInt32LE(游标 + 20)
    const 原始 = 数据.readUInt32LE(游标 + 24)
    const 名长 = 数据.readUInt16LE(游标 + 28)
    const 附加 = 数据.readUInt16LE(游标 + 30)
    const 注释 = 数据.readUInt16LE(游标 + 32)
    const 局部 = 数据.readUInt32LE(游标 + 42)
    const 名称 = 数据.toString("utf8", 游标 + 46, 游标 + 46 + 名长)
    const 局部名长 = 数据.readUInt16LE(局部 + 26)
    const 局部附加 = 数据.readUInt16LE(局部 + 28)
    const 起 = 局部 + 30 + 局部名长 + 局部附加
    条目们.push({ 名称, 方法, 压缩后, 原始, 校验和, 内容: 数据.subarray(起, 起 + 压缩后) })
    游标 += 46 + 名长 + 附加 + 注释
  }
  return { 本地头签名: 数据.readUInt32LE(0) === 0x04034b50, 条目们 }
}

