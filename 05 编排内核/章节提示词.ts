// 只负责一件事：把「本章该遵守什么」拼成一段系统提示，交给模型。
import type { 伏笔项 } from "../03 进程桥接/通道"

export interface 提示素材 {
  书名: string
  章节号: number
  章节标题: string
  伏笔: 伏笔项[]
  正文尾部: string
  额外要求?: string
}

export function 组装系统提示(素材: 提示素材): string {
  const 该兑 = 素材.伏笔.filter((x) => x.超期).slice(0, 12)
  const 久置 = 素材.伏笔.filter((x) => x.久置).slice(0, 10)
  const 待兑 = 素材.伏笔.filter((x) => x.状态 === "待兑现" && !x.超期 && !x.久置).slice(0, 10)

  const 行 = (x: 伏笔项) =>
    `- ${x.编号} ${x.名称}｜埋于 ch${x.埋章 ?? "?"}｜参考间隔 ${x.参考间隔 ?? "?"} 章` +
    (x.超期 ? `｜已超期 ${(素材.章节号 - (x.埋章 ?? 素材.章节号)) - (x.参考间隔 ?? 0)} 章` : "")

  return [
    `你在为长篇小说《${素材.书名}》工作，当前要处理第 ${素材.章节号} 章《${素材.章节标题}》。`,
    "",
    "铁律：",
    "1. 事实以设定档案与台账为准，不确定的不要编，宁可留白。",
    "2. 同一事实全书只出现一次，不重复、不改口径。",
    "3. 正文用中文，保持作者既有语感与段落节奏，不写小标题、不写总结。",
    "",
    该兑.length ? "【本章优先考虑兑现的伏笔（已超期）】" : "",
    ...该兑.map(行),
    久置.length ? "【埋了很久没动的伏笔（可择机回收）】" : "",
    ...久置.map(行),
    待兑.length ? "【仍在等待兑现的伏笔】" : "",
    ...待兑.map(行),
    素材.额外要求 ? "【作者额外要求】\n" + 素材.额外要求 : "",
    "【本章已有正文的结尾片段（用于衔接）】",
    素材.正文尾部.slice(-1200),
  ].filter((x) => x !== "").join("\n")
}
