// 只负责一件事：读写用户设置——分组建模、限界夹紧、旧文件无损迁移。
import fs from "node:fs"
import path from "node:path"
import type { 设置, 技能项 } from "../03 进程桥接/通道"
import { 默认设置 } from "./默认设置"

// 默认值只在 ./默认设置 定义一次，主进程与界面共用同一份
export { 默认设置 }

const 夹 = (值: unknown, 下限: number, 上限: number, 默认: number): number => {
  const 数 = Number(值)
  if (!Number.isFinite(数)) return 默认
  return Math.min(上限, Math.max(下限, Math.round(数 * 100) / 100))
}

const 取字 = (值: unknown, 默认: string): string => (typeof 值 === "string" ? 值 : 默认)

const 取真 = (值: unknown, 默认: boolean): boolean => (typeof 值 === "boolean" ? 值 : 默认)

function 取选<T extends string>(值: unknown, 选项: readonly T[], 默认: T): T {
  return 选项.includes(值 as T) ? (值 as T) : 默认
}

function 规范技能(原始: unknown): 技能项[] {
  if (!Array.isArray(原始)) return []
  return 原始
    .filter((项) => 项 && typeof 项 === "object")
    .slice(0, 40)
    .map((项: any) => ({
      名称: 取字(项.名称, "").slice(0, 60),
      内容: 取字(项.内容, "").slice(0, 8000),
      默认附加: 取真(项.默认附加, false),
    }))
    .filter((项) => 项.名称.length > 0)
}

/**
 * 把任何形状的设置对象揉成合法设置：
 * 1) 老的扁平结构（网关地址/API密钥/分工/项目路径）读进来后映射进分组，再写盘就只有分组了；
 * 2) 每个字段夹到上下限，手改坏了也不会崩；
 * 3) 兼容镜像永远从分组算出来，不会两边打架。
 */
export function 规范设置(原始: any): 设置 {
  const 源 = 原始 && typeof 原始 === "object" ? 原始 : {}
  const 旧 = 源
  const 新 = { ...默认设置, ...源 }
  const 模型源 = 源.模型 && typeof 源.模型 === "object" ? 源.模型 : {}
  const 外观源 = 源.外观 && typeof 源.外观 === "object" ? 源.外观 : {}
  const 编辑器源 = 源.编辑器 && typeof 源.编辑器 === "object" ? 源.编辑器 : {}
  const 上下文源 = 源.上下文 && typeof 源.上下文 === "object" ? 源.上下文 : {}
  const 智能体源 = 源.智能体 && typeof 源.智能体 === "object" ? 源.智能体 : {}
  const 书库源 = 源.书库 && typeof 源.书库 === "object" ? 源.书库 : {}

  const 分工源 = 模型源.分工 && typeof 模型源.分工 === "object" ? 模型源.分工 : 旧.分工 ?? {}
  const 人格源 = 智能体源.人格 && typeof 智能体源.人格 === "object" ? 智能体源.人格 : {}
  const 默认人格 = 默认设置.智能体.人格

  const 外观 = {
    主题: 取选(外观源.主题, ["暗", "亮", "跟随系统"] as const, 默认设置.外观.主题),
    界面字号: 夹(外观源.界面字号, 12, 18, 默认设置.外观.界面字号),
    编辑器字体: 取选(外观源.编辑器字体, ["宋体", "黑体", "系统"] as const, 默认设置.外观.编辑器字体),
    编辑器字号: 夹(外观源.编辑器字号, 13, 26, 默认设置.外观.编辑器字号),
    行距: 夹(外观源.行距, 1.2, 2.8, 默认设置.外观.行距),
    界面缩放: 夹(外观源.界面缩放, 0.8, 1.2, 默认设置.外观.界面缩放),
  }
  const 编辑器 = {
    默认模式: 取选(编辑器源.默认模式, ["源码", "分屏", "预览"] as const, 默认设置.编辑器.默认模式),
    自动保存秒: 夹(编辑器源.自动保存秒, 0, 600, 默认设置.编辑器.自动保存秒),
    显示字数: 取真(编辑器源.显示字数, 默认设置.编辑器.显示字数),
  }
  const 模型 = {
    网关地址: 取字(模型源.网关地址 ?? 旧.网关地址, 默认设置.模型.网关地址),
    API密钥: 取字(模型源.API密钥 ?? 旧.API密钥, 默认设置.模型.API密钥),
    分工: {
      总编: 取字(分工源.总编, 默认设置.模型.分工.总编),
      执笔: 取字(分工源.执笔, 默认设置.模型.分工.执笔),
      审校: 取字(分工源.审校, 默认设置.模型.分工.审校),
      助手: 取字(分工源.助手, 默认设置.模型.分工.助手),
    },
    超时秒: 夹(模型源.超时秒, 10, 600, 默认设置.模型.超时秒),
    重试次数: 夹(模型源.重试次数, 0, 5, 默认设置.模型.重试次数),
    重试间隔秒: 夹(模型源.重试间隔秒, 0, 30, 默认设置.模型.重试间隔秒),
    温度: 夹(模型源.温度, 0, 2, 默认设置.模型.温度),
    最大输出词元: 夹(模型源.最大输出词元, 256, 32000, 默认设置.模型.最大输出词元),
  }
  const 上下文 = {
    单卡注入字数: 夹(上下文源.单卡注入字数, 200, 8000, 默认设置.上下文.单卡注入字数),
    历史保留条数: 夹(上下文源.历史保留条数, 0, 100, 默认设置.上下文.历史保留条数),
    压缩触发比例: 夹(上下文源.压缩触发比例, 0.3, 1, 默认设置.上下文.压缩触发比例),
    压缩后保留条数: 夹(上下文源.压缩后保留条数, 0, 50, 默认设置.上下文.压缩后保留条数),
  }
  const 智能体 = {
    并发数: 夹(智能体源.并发数, 1, 8, 默认设置.智能体.并发数),
    阵容上限: 夹(智能体源.阵容上限, 1, 12, 默认设置.智能体.阵容上限),
    人格: {
      总编: 取字(人格源.总编, 默认人格.总编),
      审校: 取字(人格源.审校, 默认人格.审校),
      伏笔: 取字(人格源.伏笔, 默认人格.伏笔),
      台账: 取字(人格源.台账, 默认人格.台账),
      地点: 取字(人格源.地点, 默认人格.地点),
      物品: 取字(人格源.物品, 默认人格.物品),
    },
    技能: 规范技能(智能体源.技能),
  }
  const 书库 = { 上次路径: 取字(书库源.上次路径 ?? 旧.项目路径, 默认设置.书库.上次路径) }

  void 新
  return { 版本: 1, 外观, 编辑器, 模型, 上下文, 智能体, 书库 }
}

function 文件(数据目录: string): string {
  return path.join(数据目录, "设置.json")
}

export function 读设置(数据目录: string): 设置 {
  try {
    return 规范设置(JSON.parse(fs.readFileSync(文件(数据目录), "utf8")))
  } catch {
    return 规范设置({})
  }
}

export function 写设置(数据目录: string, 新设置: 设置): 设置 {
  const 合并 = 规范设置(新设置)
  fs.mkdirSync(数据目录, { recursive: true })
  fs.writeFileSync(文件(数据目录), JSON.stringify(合并, null, 2), "utf8")
  return 合并
}
