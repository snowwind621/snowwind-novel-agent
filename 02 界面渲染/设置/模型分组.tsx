// 只负责一件事：设置里的「模型」分组。
import React from "react"
import type { 模型设置 } from "../接口"
import { 分组标题, 数字项, 开关项, 文本项 } from "./共用"

const 分工键们: Array<keyof 模型设置["分工"]> = ["总编", "执笔", "审校", "助手"]

export function 模型分组(属性: {
  模型: 模型设置
  改: (补丁: Partial<模型设置>) => void
  改分工: (键: keyof 模型设置["分工"], 值: string) => void
  清单: string[]
  拉模型: () => void
  提示: string
}) {
  const { 模型, 改, 改分工, 清单, 拉模型, 提示 } = 属性
  return (
    <>
      <分组标题 文="网关" 说明="OpenAI 兼容接口" />
      <文本项 标签="网关地址" 说明="形如 http://127.0.0.1:3065/v1。" 值={模型.网关地址} 改={(值) => 改({ 网关地址: 值 })} />
      <文本项 标签="API 密钥" 说明="只存在本机，不会写进书库目录。" 值={模型.API密钥} 改={(值) => 改({ API密钥: 值 })} 密码 占位="sk-..." />
      <div className="设置项">
        <button onClick={拉模型} title="按当前网关拉一次模型清单">拉取模型清单</button>
        <span className="微信息" style={{ marginLeft: 10 }}>{提示}</span>
      </div>

      <分组标题 文="分工" 说明="四个角色各用哪个模型" />
      <div className="两列">
        {分工键们.map((键) => (
          <div className="设置项" key={键}>
            <label>{键}</label>
            {清单.length > 0 ? (
              <select value={模型.分工[键]} onChange={(事件) => 改分工(键, 事件.target.value)}>
                {清单.map((模型名) => (
                  <option key={模型名} value={模型名}>
                    {模型名}
                  </option>
                ))}
              </select>
            ) : (
              <input value={模型.分工[键]} onChange={(事件) => 改分工(键, 事件.target.value)} />
            )}
          </div>
        ))}
      </div>

      <分组标题 文="请求" 说明="超时、重试与兜底" />
      <数字项 标签="超时秒" 说明="单次请求最多等多久" 值={模型.超时秒} 最小={10} 最大={600} 改={(值) => 改({ 超时秒: 值 })} />
      <数字项 标签="重试次数" 说明="失败后自动重试几次" 值={模型.重试次数} 最小={0} 最大={5} 改={(值) => 改({ 重试次数: 值 })} />
      <数字项 标签="重试间隔秒" 说明="两次重试之间等多久" 值={模型.重试间隔秒} 最小={0} 最大={30} 改={(值) => 改({ 重试间隔秒: 值 })} />
      <开关项
        标签="请求失败时自动换下一个分工模型"
        说明="总编失败就试执笔、审校、助手，全都不行才报错。"
        值={模型.失败换模型}
        改={(值) => 改({ 失败换模型: 值 })}
      />
      <数字项 标签="单轮最大工具轮数" 说明="一轮对话里最多跑几个工具回合" 值={模型.最大工具轮} 最小={1} 最大={20} 改={(值) => 改({ 最大工具轮: 值 })} />

      <分组标题 文="采样" />
      <数字项 标签="温度" 说明="越高越发散" 值={模型.温度} 最小={0} 最大={2} 步进={0.05} 改={(值) => 改({ 温度: 值 })} />
      <数字项 标签="最大输出词元" 说明="单次回答的上限" 值={模型.最大输出词元} 最小={256} 最大={32000} 步进={256} 改={(值) => 改({ 最大输出词元: 值 })} />
    </>
  )
}
