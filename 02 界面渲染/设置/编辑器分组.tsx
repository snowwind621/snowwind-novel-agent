// 只负责一件事：设置里的「编辑器」分组。
import React from "react"
import type { 编辑器设置 } from "../接口"
import { 分组标题, 数字项, 开关项 } from "./共用"

export function 编辑器分组(属性: { 编辑器: 编辑器设置; 改: (补丁: Partial<编辑器设置>) => void }) {
  const { 编辑器, 改 } = 属性
  return (
    <>
      <分组标题 文="保存" 说明="每动一次自动保存" />
      <数字项
        标签="自动保存间隔（秒）"
        说明="改完停多久落盘；0 = 关掉自动保存"
        值={编辑器.自动保存秒}
        最小={0}
        最大={5}
        步进={0.5}
        单位="秒"
        改={(值) => 改({ 自动保存秒: 值 })}
      />
      <开关项
        标签="自动保存时做一次 Git 提交"
        说明="开着能逐次回滚；关掉只写文件，Git 里会攒成一坨。"
        值={编辑器.自动Git}
        改={(值) => 改({ 自动Git: 值 })}
      />
      <分组标题 文="编辑体验" />
      <开关项 标签="在编辑器里显示字数" 说明="关掉后工具行右端只留保存状态。" 值={编辑器.显示字数} 改={(值) => 改({ 显示字数: 值 })} />
      <数字项
        标签="撤回栈深度（步）"
        说明="Ctrl+Z 最多能往回退多少步"
        值={编辑器.撤回栈深度}
        最小={10}
        最大={500}
        步进={10}
        改={(值) => 改({ 撤回栈深度: 值 })}
      />
    </>
  )
}
