// 只负责一件事：设置里的「上下文」分组。
import React from "react"
import type { 上下文设置 } from "../接口"
import { 分组标题, 数字项, 开关项, 文本项 } from "./共用"

export function 上下文分组(属性: { 上下文: 上下文设置; 改: (补丁: Partial<上下文设置>) => void; 分工模型们: string[] }) {
  const { 上下文, 改, 分工模型们 } = 属性
  return (
    <>
      <分组标题 文="注入" 说明="每次提问都会带上的上下文" />
      <数字项 标签="单卡注入字数" 说明="每张设定卡最多塞多少字进提示" 值={上下文.单卡注入字数} 最小={200} 最大={8000} 步进={100} 改={(值) => 改({ 单卡注入字数: 值 })} />
      <开关项 标签="把上一章结尾注入提示" 说明="让模型知道「刚写到哪」，接得更顺。" 值={上下文.注入上章结尾} 改={(值) => 改({ 注入上章结尾: 值 })} />
      <数字项 标签="上一章结尾注入字数" 说明="注入多少字；太多会挤占正事" 值={上下文.注入上章字数} 最小={100} 最大={3000} 步进={50} 改={(值) => 改({ 注入上章字数: 值 })} />

      <分组标题 文="历史" 说明="对话记多少、什么时候压" />
      <数字项 标签="历史保留条数" 说明="对话里保留多少条原文" 值={上下文.历史保留条数} 最小={0} 最大={100} 改={(值) => 改({ 历史保留条数: 值 })} />
      <数字项 标签="压缩触发比例" 说明="上下文用到这个比例就开始压缩" 值={上下文.压缩触发比例} 最小={0.3} 最大={1} 步进={0.05} 改={(值) => 改({ 压缩触发比例: 值 })} />
      <数字项 标签="压缩后保留条数" 说明="压完留多少条" 值={上下文.压缩后保留条数} 最小={0} 最大={50} 改={(值) => 改({ 压缩后保留条数: 值 })} />

      <分组标题 文="摘要" />
      <文本项
        标签="摘要用哪个模型"
        说明={"留空 = 用「助手」那个分工。" + (分工模型们.length > 0 ? "可选：" + 分工模型们.join("、") : "")}
        值={上下文.摘要模型}
        改={(值) => 改({ 摘要模型: 值 })}
        占位="留空 = 助手"
      />
    </>
  )
}
