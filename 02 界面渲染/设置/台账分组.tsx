// 只负责一件事：设置里的「台账」分组（自动同步开关、静置秒、失败重试）。
import React from "react"
import type { 台账设置 } from "../接口"
import { 分组标题, 数字项, 开关项 } from "./共用"

export function 台账分组(属性: { 台账: 台账设置; 改: (补丁: Partial<台账设置>) => void }) {
  const { 台账, 改 } = 属性
  return (
    <>
      <分组标题 文="自动同步" 说明="停手之后才跑，不跟保存抢" />
      <开关项
        标签="保存后自动同步台账"
        说明="关掉后连「待同步」标记都不记；手动「立即同步」仍然可用。"
        值={台账.自动同步}
        改={(值) => 改({ 自动同步: 值 })}
      />
      <数字项
        标签="停手多少秒后开跑"
        说明="改完最后一笔，静置这么久才去读正文、更新台账"
        值={台账.静置秒}
        最小={5}
        最大={120}
        单位="秒"
        改={(值) => 改({ 静置秒: Math.round(值) })}
      />
      <数字项
        标签="失败后自动重试次数"
        说明="用完就把这一章停在「同步失败」，等你点「立即重试」"
        值={台账.失败重试次数}
        最小={0}
        最大={2}
        改={(值) => 改({ 失败重试次数: Math.round(值) })}
      />
      <分组标题 文="说明" />
      <div className="设置说明">
        编辑器工具行右端会显示这一章的台账状态（已同步 / 待同步 / 同步中 / 失败）；点状态能看到上次同步的用时与 token。
      </div>
    </>
  )
}
